<?php

namespace App\Http\Requests;

use Closure;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Http\UploadedFile;
use Illuminate\Validation\Rules\File;

class StoreTicketRequest extends FormRequest
{
    public function authorize(): bool
    {
        return $this->user() !== null;
    }

    protected function prepareForValidation(): void
    {
        // "Other / I'm not sure" may arrive
        // as an empty string from FormData.
        if ($this->input('system_category_id') === '') {
            $this->merge([
                'system_category_id' => null,
            ]);
        }
    }

    public function rules(): array
    {
        $extensions = [
            'jpg',
            'jpeg',
            'png',
            'webp',
            'pdf',
            'doc',
            'docx',
            'xls',
            'xlsx',
        ];

        return [
            'ticket_type_id' => [
                'required',
                'integer',
                'exists:categories,id',
            ],

            'system_id' => [
                'required',
                'integer',
                'exists:systems,id',
            ],

            'system_category_id' => [
                'nullable',
                'integer',
                'exists:system_categories,id',
            ],

            'description' => [
                'required',
                'string',
                'max:10000',
            ],

            'attachments' => [
                'sometimes',
                'array',
                'max:10',
            ],

            'attachments.*' => [
                'bail',
                'required',
                'file',

                // Check the user's file extension.
                'extensions:' . implode(',', $extensions),

                // Check the actual file content type.
                File::types($extensions),

                // Exactly 2 MiB is NOT allowed.
                function (
                    string $attribute,
                    mixed $value,
                    Closure $fail
                ): void {
                    if (
                        $value instanceof UploadedFile &&
                        $value->getSize() >= 2097152
                    ) {
                        $fail(
                            'Each attachment must be smaller than 2 MB.'
                        );
                    }
                },
            ],

            // These values must always be
            // generated by Laravel.
            'ticket_number' => ['prohibited'],
            'requester_id' => ['prohibited'],
            'priority_id' => ['prohibited'],
            'status_id' => ['prohibited'],

            // Future administrative fields cannot
            // be supplied by a requester.
            'assigned_by_id' => ['prohibited'],
            'assigned_operator_id' => ['prohibited'],
            'assigned_at' => ['prohibited'],
            'resolution_note' => ['prohibited'],
            'resolved_at' => ['prohibited'],
        ];
    }

    public function messages(): array
    {
        return [
            'ticket_type_id.required' =>
            'Please select a ticket type.',

            'system_id.required' =>
            'Please select the system you need help with.',

            'description.required' =>
            'Please describe what happened so we can help.',

            'attachments.max' =>
            'You can attach up to 5 files.',

            'attachments.*.file' =>
            'Please select a valid image or document.',

            'attachments.*.extensions' =>
            'Only JPG, PNG, WebP, PDF, Word, and Excel files are allowed.',

            'attachments.*.mimes' =>
            'The attachment file type is not supported.',

            'ticket_number.prohibited' =>
            'Ticket numbers are generated automatically.',
        ];
    }
}
